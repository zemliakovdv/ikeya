export function usePvzData() {
  const [points,       setPoints]       = useState([]);
  const [filtered,     setFiltered]     = useState([]);
  const [activeFilter, setActiveFilter] = useState('all');
  const [search,       setSearch]       = useState('');
  const [loading,      setLoading]      = useState(true);

  const searchTimer = useRef(null);

  useEffect(() => {
    async function loadAll() {
      setLoading(true);
      try {
        const [pvzRes, euroRes, autoRes] = await Promise.allSettled([
          fetch(`${API_BASE_URL}/delivery/pickup_points`),
          fetch(`${API_BASE_URL}/delivery/europost_offices`),
          fetch(`${API_BASE_URL}/delivery/autolight_offices`),
        ]);

        const pvzPoints = pvzRes.status === 'fulfilled' && pvzRes.value.ok
          ? ((await pvzRes.value.json()).pickup_points || []).map(p => normalizePoint(p, 'pvz'))
          : [];

        const euroPoints = euroRes.status === 'fulfilled' && euroRes.value.ok
          ? ((await euroRes.value.json()).offices || []).map(o => normalizePoint(o, 'europost'))
          : [];

        const autoPoints = autoRes.status === 'fulfilled' && autoRes.value.ok
          ? ((await autoRes.value.json()).offices || []).map(o => normalizePoint(o, 'autolight'))
          : [];

        const all = [...pvzPoints, ...euroPoints, ...autoPoints];
        setPoints(all);
        setFiltered(all);
      } catch (e) {
        console.error('Ошибка загрузки ПВЗ:', e);
      } finally {
        setLoading(false);
      }
    }
    loadAll();
  }, []);

  useEffect(() => {
    let result = [...points];
    if (activeFilter !== 'all') {
      result = result.filter(p => p.provider === activeFilter);
    }
    if (search.trim()) {
      const q = search.toLowerCase();
      result = result.filter(p =>
        p.address?.toLowerCase().includes(q) ||
        p.city?.toLowerCase().includes(q) ||
        p.name?.toLowerCase().includes(q)
      );
    }
    setFiltered(result);
  }, [activeFilter, search, points]);

  const handleSearch = useCallback((e) => {
    const val = e.target.value;
    clearTimeout(searchTimer.current);
    searchTimer.current = setTimeout(() => setSearch(val), 300);
  }, []);

  return {
    filtered,
    activeFilter,
    setActiveFilter,
    loading,
    handleSearch,
  };
}