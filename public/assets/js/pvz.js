// Рендер меток на карте
function renderMap(data) {
  // Удаляем старые метки
  placemarks.forEach(p => map.geoObjects.remove(p));
  placemarks = [];
  
  // Добавляем новые метки с кастомными иконками
  data.forEach(p => {
    const pm = new ymaps.Placemark(p.coords, {
      hintContent: p.title
    }, {
      iconLayout: 'default#image',
      iconImageHref: createIconDataUrl(p.type),
      iconImageSize: [32, 32],
      iconImageOffset: [-16, -16]
    });
    
    map.geoObjects.add(pm);
    placemarks.push(pm);
  });
}

// Привязка кликов к карточкам
function bindClicks() {
  document.querySelectorAll('.pvz-card').forEach(card => {
    card.onclick = () => {
      document.querySelectorAll('.pvz-card').forEach(c => c.classList.remove('active'));
      card.classList.add('active');
      
      const p = pvzData.find(x => x.id == card.dataset.id);
      map.setCenter(p.coords, 14);
    };
  });
}

// Обработка фильтров
document.querySelectorAll('.map-filters button').forEach(btn => {
  btn.onclick = () => {
    document.querySelectorAll('.map-filters button').forEach(b => b.classList.remove('active'));
    btn.classList.add('active');
    applyFilter(btn.dataset.filter);
  };
});
